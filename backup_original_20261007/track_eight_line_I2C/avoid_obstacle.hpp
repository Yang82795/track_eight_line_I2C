#ifndef __AVOID_OBSTACLE_HPP_
#define __AVOID_OBSTACLE_HPP_

#include <Arduino.h>
#include <HCSR04.h>
#include "motor_car.hpp"
#include "line_pid.hpp"

// =========================================================================
// ★★★ 0. 避障功能总开关 (4种工作模式，现场按需一键切换) ★★★
// =========================================================================
// 0: 【全关】彻底关闭避障 (纯循迹模式，完全不读取超声波，0耗时，100%杜绝误报)
// 1: 【只左】仅启用左侧超声波 (★当前过渡期首选推荐★：右侧超声波未到时专用，向右绕障)
// 2: 【只右】仅启用右侧超声波 (右侧超声波单独调试专用，向左绕障)
// 3: 【全开 / 开】左右双超声波同时启用 (双向全自动避障：左见障右绕，右见障左绕)

#define AVOID_MODE_OFF        0   // 全关：纯循迹
#define AVOID_MODE_LEFT_ONLY  1   // 只左：仅用左超声波 (★当前默认推荐★)
#define AVOID_MODE_RIGHT_ONLY 2   // 只右：仅用右超声波
#define AVOID_MODE_ALL_ON     3   // 全开：左右双超声波同时自动避障

// ↓↓↓【总开关位置】现场修改此处的数值 (0 / 1 / 2 / 3) 即可切换模式 ↓↓↓
#define AVOID_SWITCH_MODE     AVOID_MODE_ALL_ON

// =========================================================================
// ★★★ 1. 硬件引脚配置 (左右双超声波 HC-SR04) ★★★
// =========================================================================
// 【左侧超声波】(当前车上已实装并在用)
#define TRIG_PIN_LEFT         2    // 左侧超声波 Trig 引脚
#define ECHO_PIN_LEFT         3    // 左侧超声波 Echo 引脚

// 【右侧超声波】(替代原红外位置，等右侧模块到货后接此引脚)
// 重要提示：Arduino Uno 的 A4 是 SDA，A5 是 SCL，已被 8 路循迹占用！
// A3 与 A2 是最理想的通用数字引脚 (对应引脚编号 17 和 16)，插上即用。
#define TRIG_PIN_RIGHT        11   // 右侧超声波 Trig 引脚 (默认 A3)
#define ECHO_PIN_RIGHT        12   // 右侧超声波 Echo 引脚 (默认 A2)

// =========================================================================
// ★★★ 2. 障碍物触发距离与判定灵敏度 ★★★
// =========================================================================
#define AVOID_TRIGGER_CM_LEFT   35  // 左侧超声波触发距离 (单位: cm，推荐 22~28cm)
#define AVOID_TRIGGER_CM_RIGHT  35  // 右侧超声波触发距离 (单位: cm，推荐 22~28cm)
#define AVOID_CONFIRM_TIMES     2   // 连续确认次数 (连续2次检测到障碍才触发，防单次偶发杂波)
#define AVOID_PRIORITY_DIR      2   // 双侧同时触发时的优先方向 (2: 优先向右绕, 1: 优先向左绕)

// =========================================================================
// ★★★ 3. 新电机避障速度设置 (已根据 6.0 新电机 Speed_Line=50 精准匹配) ★★★
// =========================================================================
#define SPEED_TURN_OUT_FAST   60   // 第1阶段偏出：外侧轮快速 (推荐 80~95)
#define SPEED_TURN_OUT_SLOW   20   // 第1阶段偏出：内侧轮慢速 (推荐 15~25，大于新电机死区10)

#define SPEED_PASS_FAST       60   // 第2阶段超越：外侧轮快速 (推荐 80~95)
#define SPEED_PASS_SLOW       20   // 第2阶段超越：内侧轮慢速 (推荐 15~25)

#define SPEED_RETURN          50   // 第3阶段直走切回黑线：双轮等速 (推荐 45~55，完全契合巡线速度50)

#define SPEED_ALIGN_FAST      50   // 第4阶段触线拉直：外侧轮微调 (推荐 45~55)
#define SPEED_ALIGN_SLOW      20   // 第4阶段触线拉直：内侧轮微调 (推荐 15~25)

// =========================================================================
// ★★★ 4. 动作时序与角度调节 (现场调小车转角只需改这几个毫秒数！) ★★★
// =========================================================================
#define TIME_INITIAL_STOP_MS  350  // 刚发现障碍物时的刹停稳定时间 (ms)
#define TIME_TURN_OUT_MS      350  // 第1阶段偏出时长 (ms，转角约45度；如偏出不够加大，偏出太多减小)
#define TIME_PAUSE_MS         80   // 动作交替刹停缓冲 (ms，消解轮组转动惯性，绝不连带甩尾)
#define TIME_PASS_MS          700 // 第2阶段弧线超越时长 (ms，如回转角度不够加大，如转过头减小)
#define TIME_RETURN_MAX       3500 // 第3阶段直走回线最大超时 (ms，放宽至3.5秒，红外见线立即急停，绝不中途误退)
#define TIME_ALIGN_MS         100  // 第4阶段触线微调拉直时长 (ms，顺势扶正车身平行黑线)

// =========================================================================
// ★★★ 5. 避障安全保护参数 ★★★
// =========================================================================
#define AVOID_COOLDOWN_MS      1500 // 避障完成后屏蔽超声波时间 (ms)，防对同一障碍二次误触发
#define AVOID_FINISH_SHIELD_MS 5000 // 避障完成后屏蔽终点线误判时间 (ms)，防回线瞬间因多路黑线误刹停！

// =========================================================================
// 接口与状态枚举定义
// =========================================================================
enum ObstacleSide {
  OBS_NONE  = 0, // 无障碍物
  OBS_LEFT  = 1, // 左侧(左超声波)检测到障碍 -> 需向右绕行
  OBS_RIGHT = 2, // 右侧(右超声波)检测到障碍 -> 需向左绕行
  OBS_BOTH  = 3  // 左右两侧均有障碍         -> 按优先方向绕行
};

extern unsigned long g_shield_finish_until; // 避障后终点线屏蔽截止时刻

void Avoid_init(void);
ObstacleSide Avoid_detect(void);                   // 实时检测两侧障碍，返回侧别 (0=无障碍)
void Avoid_perform(ObstacleSide side = OBS_NONE);  // 执行避障动作

#endif
